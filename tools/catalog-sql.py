#!/usr/bin/env python3
"""Write the catalogue block of the latest server/database/db_v<N>_init.sql (categories, weapons,
sections and techniques, with their translations) from
server/database/catalog/techniques.json, the file to edit.

    python3 tools/catalog-sql.py            rewrite the block
    python3 tools/catalog-sql.py --check    exit 1 if the block is out of date (tests)

IDs: section <ryu>.<category>[.<weapon>].<id>, technique <section>.<id>;
translation IDs <table>.<id>.description. Rows keep the JSON's order (rowid order
is the display order).
"""

import json
import sys
from pathlib import Path

DATABASE = Path(__file__).resolve().parent.parent / "server" / "database"
SOURCE = DATABASE / "catalog" / "techniques.json"
# The newest version's seed: older ones are frozen (the databases built from them are
# migrated, migrations/).
TARGET = max(DATABASE.glob("db_v*_init.sql"), key=lambda p: int(p.name[4:-9]))
BEGIN = "-- BEGIN catalogue: generated by tools/catalog-sql.py from catalog/techniques.json, do not edit by hand."
END = "-- END catalogue"


def quote(value) -> str:
    return "NULL" if value is None else "'" + str(value).replace("'", "''") + "'"


def insert(table: str, columns: tuple[str, ...], rows: list[tuple]) -> str:
    head = f'INSERT INTO "{table}" (' + ", ".join(f'"{c}"' for c in columns) + ") VALUES\n"
    return head + ",\n".join("\t(" + ", ".join(quote(v) for v in row) + ")" for row in rows) + ";\n"


def section_id(ryu: str, section: dict) -> str:
    return ".".join(p for p in (ryu, section["category"], section["weapon"], section["id"]) if p)


def block(catalog: dict) -> str:
    translations, categories, weapons, sections, techniques = [], [], [], [], []
    for table, rows, out in (("category", catalog["categories"], categories), ("weapon", catalog["weapons"], weapons)):
        for row in rows:
            tid = f"{table}.{row['id']}.description"
            translations.append((tid, row["en"], row["fr"]))
            out.append((row["id"], row["kanji"], row["romaji"], tid))
    for school in catalog["schools"]:
        for section in school["sections"]:
            sid = section_id(school["ryu"], section)
            translations.append((f"section.{sid}.description", section["en"], section["fr"]))
            sections.append((sid, school["ryu"], section["category"], section["weapon"], section["kanji"],
                             section["romaji"], f"section.{sid}.description"))
            for technique in section["techniques"]:
                tid = f"{sid}.{technique['id']}"
                translations.append((f"technique.{tid}.description", technique["en"], technique["fr"]))
                techniques.append((tid, technique["kanji"], technique["romaji"], sid, f"technique.{tid}.description"))
    return "\n".join([
        BEGIN,
        insert("translation", ("id", "en", "fr"), translations),
        insert("category", ("id", "kanji", "romaji", "description"), categories),
        insert("weapon", ("id", "kanji", "romaji", "description"), weapons),
        insert("section", ("id", "ryu", "category", "weapon", "kanji", "romaji", "description"), sections),
        insert("technique", ("id", "kanji", "romaji", "section", "description"), techniques) + END,
    ])


def main() -> None:
    text = TARGET.read_text(encoding="utf-8")
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        sys.exit(f"catalog-sql: markers not found in {TARGET}")
    wanted = text[:start] + block(json.loads(SOURCE.read_text(encoding="utf-8"))) + text[end + len(END):]
    if "--check" in sys.argv[1:]:
        if wanted != text:
            sys.exit(f"catalog-sql: {TARGET.name} is out of date: run python3 tools/catalog-sql.py")
        return
    if wanted != text:
        TARGET.write_text(wanted, encoding="utf-8")
        print(f"Wrote the catalogue block of {TARGET}")


if __name__ == "__main__":
    main()
