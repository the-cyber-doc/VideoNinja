CREATE TABLE IF NOT EXISTS "config" (
	"name" VARCHAR NOT NULL UNIQUE,
	"type" VARCHAR NOT NULL,
	"value" VARCHAR NOT NULL,
	PRIMARY KEY("name")
);

CREATE TABLE IF NOT EXISTS "ryu" (
	"id" VARCHAR NOT NULL UNIQUE,
	"kanji" VARCHAR NOT NULL,
	"romaji" VARCHAR NOT NULL,
	"description" TEXT,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "level" (
	"id" VARCHAR NOT NULL UNIQUE,
	"kanji" VARCHAR NOT NULL,
	"romaji" VARCHAR NOT NULL,
	"description" TEXT,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "technique" (
	"id" VARCHAR NOT NULL UNIQUE,
	"kanji" VARCHAR NOT NULL,
	"romaji" VARCHAR NOT NULL,
	"ryu" VARCHAR NOT NULL,
	"level" VARCHAR NOT NULL,
	PRIMARY KEY("id"),
	FOREIGN KEY ("level") REFERENCES "level"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION,
	FOREIGN KEY ("ryu") REFERENCES "ryu"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS "video" (
	"id" INTEGER NOT NULL UNIQUE,
	"sha256sum" TEXT NOT NULL UNIQUE,
	"filename" VARCHAR NOT NULL,
	"directory" VARCHAR NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "sequence" (
	"id" INTEGER NOT NULL UNIQUE,
	"video" INTEGER NOT NULL,
	"technique" VARCHAR NOT NULL,
	"begin" INTEGER NOT NULL,
	"end" INTEGER NOT NULL,
	"performer" VARCHAR NOT NULL,
	PRIMARY KEY("id"),
	FOREIGN KEY ("video") REFERENCES "video"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION,
	FOREIGN KEY ("technique") REFERENCES "technique"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION,
	FOREIGN KEY ("performer") REFERENCES "performer"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS "comment" (
	"id" INTEGER NOT NULL UNIQUE,
	"technique" VARCHAR NOT NULL,
	"user" INTEGER NOT NULL,
	PRIMARY KEY("id"),
	FOREIGN KEY ("technique") REFERENCES "technique"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION,
	FOREIGN KEY ("user") REFERENCES "user"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS "tag" (
	"id" VARCHAR NOT NULL UNIQUE,
	"fixed_values" BOOLEAN NOT NULL,
	"list_of_values" VARCHAR,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "video_has_tags" (
	"video" INTEGER NOT NULL,
	"tag" VARCHAR NOT NULL,
	"value" VARCHAR,
	PRIMARY KEY("video", "tag"),
	FOREIGN KEY ("video") REFERENCES "video"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION,
	FOREIGN KEY ("tag") REFERENCES "tag"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS "sequence_has_tags" (
	"sequence" INTEGER NOT NULL,
	"tag" VARCHAR NOT NULL,
	"value" VARCHAR,
	PRIMARY KEY("sequence", "tag"),
	FOREIGN KEY ("sequence") REFERENCES "sequence"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION,
	FOREIGN KEY ("tag") REFERENCES "tag"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS "user" (
	"id" INTEGER NOT NULL UNIQUE,
	"username" VARCHAR NOT NULL UNIQUE,
	"name" VARCHAR,
	"pw_hash" TEXT NOT NULL,
	"totp" VARCHAR NOT NULL,
	"role" VARCHAR NOT NULL,
	PRIMARY KEY("id"),
	FOREIGN KEY ("role") REFERENCES "role"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS "role" (
	"id" VARCHAR NOT NULL UNIQUE,
	"name" VARCHAR NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "access" (
	"id" VARCHAR NOT NULL UNIQUE,
	"name" VARCHAR NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "role_has_access" (
	"role" VARCHAR NOT NULL,
	"access" VARCHAR NOT NULL,
	PRIMARY KEY("role", "access"),
	FOREIGN KEY ("role") REFERENCES "role"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION,
	FOREIGN KEY ("access") REFERENCES "access"("id")
	ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE IF NOT EXISTS "performer" (
	"id" VARCHAR NOT NULL,
	"name" VARCHAR NOT NULL,
	PRIMARY KEY("id")
);

